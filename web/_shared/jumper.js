      if (B.mouth > 0 && Math.floor(t * 16) % 2) { g.globalCompositeOperation = "lighter"; g.drawImage(art.glowOf("#ff2e63", 40), x + spr.width / 2 - 40, y + spr.height / 2 - 40); g.globalCompositeOperation = "source-over"; }
