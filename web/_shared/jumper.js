    B.x += B.vx * dt;
    if (B.x < A.x0 + 4) { B.x = A.x0 + 4; B.vx = Math.abs(B.vx); }
    if (B.x + B.w > A.x1 - TS - 4) { B.x = A.x1 - TS - 4 - B.w; B.vx = -Math.abs(B.vx); }
