    // ───── 고정 간격 반복
    let lastT = performance.now(), acc = 0;
    function frame(now) {
      const dt = Math.min(0.1, Math.max(0, (now - lastT) / 1000)); lastT = now;
      clock += dt;
      if (scene !== "paused" && scene !== "title" && scene !== "result") {
        acc += dt;
        while (acc >= STEP) {
          acc -= STEP; sceneT += STEP;
          if (scene === "play") stepPlay(STEP);
          else if (scene === "intro") { if (sceneT > 2.4) { setScene("play"); music.start(MAPS[si].bgm); } }
          else if (scene === "bossintro") { W.t += STEP; W.bossIntro -= STEP; updateCam(STEP); if (W.bossIntro <= 0) { setScene("play"); music.start(6); } }
          else if (scene === "door") stepDoor(STEP);
          else if (scene === "dying") stepDying(STEP);
          else if (scene === "flag") stepFlag(STEP);
          else if (scene === "tally") stepTally(STEP);
          else if (scene === "ending") stepEnding(STEP);
          else if (scene === "gameover") { if (sceneT > 2.6 && !resultShown) finish(false); }
          if (scene === "paused" || scene === "result") break;
        }
      } else { acc = 0; if (scene === "result" && ending && ending.t < 12) ending.t += dt; }
      if (G) updateHud();
      render();
      requestAnimationFrame(frame);
    }

