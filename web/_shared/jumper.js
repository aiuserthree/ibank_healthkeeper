  // 덩어리 → 한 장의 타일 맵 (+ 방 경계)
  function build(def) {
    const rows = Array.from({ length: ROWS }, () => "");
    const rooms = [];
    let start = 0;
    const errors = [];
    def.segs.forEach((sg, si) => {
      if (sg === ROOM) { rooms.push([start, rows[0].length - 1]); start = rows[0].length; return; }
      if (sg.length !== ROWS) errors.push(`${def.id} 덩어리 ${si}: 줄 수 ${sg.length}`);
      const w = sg[0].length;
      for (let r = 0; r < ROWS; r++) {
        const line = sg[r] || "";
        if (line.length !== w) errors.push(`${def.id} 덩어리 ${si} ${r}줄: 길이 ${line.length} ≠ ${w}`);
        rows[r] += line.padEnd(w, ".").slice(0, w);
      }
    });
    rooms.push([start, rows[0].length - 1]);
    return { ...def, rows, w: rows[0].length, h: ROWS, rooms, errors };
  }
