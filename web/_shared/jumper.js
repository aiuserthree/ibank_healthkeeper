  // pose: stand0 stand1 walk0-3 run0-3 jump fall skid crouch die pole cheer  · size: 0 작음(20×32) 1 큼(24×42)
  function paintHero(pose, big, coatRamp, blink) {
    const W = big ? 24 : 20, H = big ? 42 : 32;
    const px = new Px(W, H);
    const P = {
      bag: px.part(PAL.bag), legB: px.part(PAL.pants), shoeB: px.part(PAL.shoe), armB: px.part(coatRamp),
      body: px.part(coatRamp), shirt: px.part(PAL.shirt), legF: px.part(PAL.pants), shoeF: px.part(PAL.shoe),
      head: px.part(PAL.skin), hair: px.part(PAL.hair), armF: px.part(coatRamp), hand: px.part(PAL.skin),
    };
    const cx = W / 2;
    let bob = 0, legA = 0, legB = 0, liftA = 0, liftB = 0, armA = 0, lean = 0, crouch = 0;
    const walk = /^walk|^run/.test(pose) ? +pose.slice(-1) : -1;
    if (walk >= 0) {
      const run = pose.startsWith("run");
      const s = run ? 3 : 2;
      legA = [s, 0, -s, 0][walk]; legB = -legA; liftA = [0, 1, 0, 0][walk] + (run && walk === 0 ? 1 : 0); liftB = [0, 0, 0, 1][walk] + (run && walk === 2 ? 1 : 0);
      bob = walk % 2 ? -1 : 0; armA = -legA; lean = run ? 1 : 0;
    }
    if (pose === "stand1") bob = 1;
    if (pose === "jump") { legA = 2; legB = -2; liftA = 3; liftB = 1; armA = -3; bob = -1; }
    if (pose === "fall") { legA = 1; legB = -1; liftA = 1; liftB = 2; armA = 3; }
    if (pose === "skid") { legA = 3; legB = 2; armA = 3; lean = -1; }
    if (pose === "crouch") crouch = big ? 12 : 7;
    if (pose === "pole") { legA = 1; legB = -1; armA = -4; }
    if (pose === "cheer") { armA = -5; bob = -1; }
    const headR = big ? 7.6 : 7.2;
    const headCy = (big ? 11 : 10) + bob + crouch;
    const bodyTop = (big ? 18 : 16) + bob + crouch;
    const bodyH = big ? 15 : 9;
    const legTop = bodyTop + bodyH - 1;
    const legH = Math.max(2, H - legTop - 2);
    const bx = Math.round(cx - (big ? 5 : 4) + lean);
    const bw = big ? 11 : 9;
    // 도시락 가방 — 뒤 손에 들고 흔든다
    const bagX = bx - 3 + Math.round(-armA * 0.6), bagY = bodyTop + (big ? 9 : 5) + (pose === "cheer" ? -2 : 0);
    if (pose !== "die") { px.box(bagX - 2, bagY, 6, 5, P.bag, 0.05, 1); px.line(bagX - 1, bagY - 1, bagX + 2, bagY - 1, PAL.bag[0]); }
    // 다리 (뒤 → 앞)
    const leg = (dx, lift, pl, ps, bright) => {
      if (crouch) { px.box(bx + 1 + dx, H - 5, 4, 3, pl, bright); px.box(bx + dx, H - 3, 6, 3, ps, bright); return; }
      px.box(bx + 2 + dx, legTop, 4, legH - lift, pl, bright, 0);
      px.box(bx + 1 + dx, H - 3 - lift, 6, 3, ps, bright, 1);
    };
    if (pose !== "die") { leg(Math.round(legB * 0.8) - 1, liftB, P.legB, P.shoeB, -0.15); }
    // 뒤 팔
    if (pose !== "die" && pose !== "crouch") px.box(bx - 1 + Math.round(-armA * 0.5), bodyTop + 1, 3, bodyH - 2, P.armB, -0.15, 1);
    // 몸 — 가디건 + 셔츠 + 사원증 목걸이
    if (pose === "die") {
      px.box(bx, bodyTop, bw, bodyH, P.body, 0, 2);
      px.box(bx - 3, bodyTop - 2, 3, 6, P.armF, 0, 1); px.box(bx + bw, bodyTop - 2, 3, 6, P.armF, 0, 1);
      px.box(bx + 1, legTop, 3, legH, P.legF); px.box(bx + bw - 4, legTop, 3, legH, P.legF);
    } else {
      px.box(bx, bodyTop, bw, bodyH, P.body, 0, 2);
      px.box(bx + Math.floor(bw / 2) - 1, bodyTop, 3, Math.min(bodyH - 2, big ? 9 : 5), P.shirt, 0.1, 0);
      leg(Math.round(legA * 0.8), liftA, P.legF, P.shoeF, 0);
    }
    // 머리 — 둥근 얼굴, 뒤로 넘긴 머리카락, 앞머리
    const hx = cx + (pose === "die" ? 0 : 0.6) + lean * 0.5;
    px.ell(hx, headCy, headR, headR * 0.95, P.head, 0.05);
    px.ell(hx - 1.2, headCy - 2.6, headR + 0.4, headR * 0.72, P.hair, 0);
    // 얼굴 쪽은 머리카락을 걷어 낸다 (앞머리 몇 가닥만)
    for (let y = Math.round(headCy - 2); y <= Math.round(headCy + headR); y++) for (let x = Math.round(hx - 3); x <= Math.round(hx + headR); x++) {
      const nx = (x + 0.5 - hx) / headR, ny = (y + 0.5 - headCy) / (headR * 0.95);
      if (nx * nx + ny * ny <= 0.92 && px.pid(x, y) === P.hair && y > headCy - 3 + (x % 3 === 0 ? -1 : 0)) px.set(x, y, px.tone(P.head, 0.62 - ny * 0.25 - nx * 0.1, x, y), P.head);
    }
    // 정수리 뻗친 머리 (실루엣 포인트)
    px.set(hx - 1, headCy - headR - 1, PAL.hair[1], P.hair); px.set(hx, headCy - headR - 2, PAL.hair[2], P.hair); px.set(hx + 1, headCy - headR - 2, PAL.hair[1], P.hair);
    // 앞 팔 + 손 (외곽선 전에)
    if (pose !== "crouch" && pose !== "die") {
      const ax = bx + bw - 3 + Math.round(armA * 0.5);
      if (pose === "jump") { px.box(ax + 1, bodyTop + 1, 6, 3, P.armF, 0.05, 1); px.ell(ax + 7, bodyTop + 2.5, 1.8, 1.8, P.hand, 0.1); }
      else if (pose === "cheer" || pose === "pole") { px.box(ax + 2, bodyTop - 4, 3, 7, P.armF, 0.05, 1); px.ell(ax + 3.5, bodyTop - 4.5, 1.8, 1.8, P.hand, 0.1); }
      else { px.box(ax, bodyTop + 1, 3, bodyH - 2, P.armF, 0.05, 1); px.ell(ax + 1.5, bodyTop + bodyH - 1, 1.8, 1.8, P.hand, 0.1); }
    }
    px.outline();
    // 눈 · 볼 · 입 (외곽선 뒤에 찍는다)
    const ey = Math.round(headCy + 1), e1 = Math.round(hx - 0.5), e2 = Math.round(hx + 3.5);
    if (pose === "die") {
      [[e1 - 2, ey], [e2 - 2, ey]].forEach(([x, y]) => { px.set(x - 1, y - 1, PAL.ink); px.set(x + 1, y + 1, PAL.ink); px.set(x, y, PAL.ink); px.set(x + 1, y - 1, PAL.ink); px.set(x - 1, y + 1, PAL.ink); });
      px.set(cx, ey + 3, PAL.ink); px.set(cx + 1, ey + 3, PAL.ink); px.set(cx, ey + 4, PAL.skin[0]);
    } else if (pose === "cheer" || pose === "pole") {
      [e1, e2].forEach((x) => { px.set(x - 1, ey, PAL.ink); px.set(x, ey - 1, PAL.ink); px.set(x + 1, ey, PAL.ink); });
      px.set(e1 + 2, ey + 3, PAL.skin[0]); px.set(e1 + 3, ey + 4, "#ff6a7a"); px.set(e1 + 4, ey + 3, PAL.skin[0]);
    } else if (blink) {
      [e1, e2].forEach((x) => { px.set(x, ey, PAL.ink); px.set(x + 1, ey, PAL.ink); });
    } else {
      const det = pose === "jump" || pose.startsWith("run") || pose === "skid";
      [e1, e2].forEach((x) => {
        px.set(x, ey - 1, PAL.ink); px.set(x, ey, PAL.ink); px.set(x, ey + 1, PAL.ink); px.set(x + 1, ey, PAL.ink); px.set(x + 1, ey + 1, PAL.ink);
        px.set(x + 1, ey - 1, det ? PAL.ink : PAL.cream);
        if (det) px.set(x - 1, ey - 2, PAL.hair[1]);
      });
      px.set(e1 + 2, ey + 3, pose === "skid" ? PAL.ink : PAL.skin[0]); px.set(e1 + 3, ey + 3, PAL.skin[0]);
    }
    px.set(e1 - 2, ey + 2, PAL.blush); px.set(e2 + 1, ey + 2, PAL.blush);
    // 사원증 목걸이 + 카드
    if (pose !== "die") {
      const ny = bodyTop, mx = bx + Math.floor(bw / 2);
      px.set(mx - 2, ny, PAL.lanyard[1]); px.set(mx - 1, ny + 1, PAL.lanyard[1]); px.set(mx + 2, ny, PAL.lanyard[1]); px.set(mx + 2, ny + 1, PAL.lanyard[0]);
      const cy0 = ny + (big ? 4 : 2);
      for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++) px.set(mx - 1 + x + 1, cy0 + y, y === 0 ? PAL.card[2] : x === 0 ? PAL.card[0] : PAL.card[1]);
    }
    return px;
  }
