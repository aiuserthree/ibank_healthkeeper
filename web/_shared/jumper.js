        W.shake = Math.max(W.shake, 0.2); emit(W, "slam");
        puff(W, B.x + B.w / 2, ground, 14, [THEMES[W.theme].dust, "#fff6e0"], 90, 0.5, -40);
        if (B.leap) { [-1, 1].forEach((d) => W.shots.push({ kind: "wave", x: B.x + B.w / 2 - 6 + d * 30, y: ground - 10, w: 12, h: 10, vx: d * 150, vy: 0, t: 0 })); }
