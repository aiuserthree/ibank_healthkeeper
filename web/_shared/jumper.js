  const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5].map((v) => v / 16 - 0.47);
  const mkCanvas = (w, h) => { const c = document.createElement("canvas"); c.width = w; c.height = h; return c; };
  class Px {
    constructor(w, h) { this.w = w; this.h = h; this.c = new Array(w * h).fill(null); this.p = new Int16Array(w * h).fill(-1); this.ramps = []; }
    part(ramp, line = true) { this.ramps.push({ ramp, line }); return this.ramps.length - 1; }
    set(x, y, col, pid = -1) { x = Math.round(x); y = Math.round(y); if (x < 0 || y < 0 || x >= this.w || y >= this.h) return; this.c[y * this.w + x] = col; this.p[y * this.w + x] = pid; }
    get(x, y) { return x < 0 || y < 0 || x >= this.w || y >= this.h ? null : this.c[y * this.w + x]; }
    pid(x, y) { return x < 0 || y < 0 || x >= this.w || y >= this.h ? -1 : this.p[y * this.w + x]; }
    tone(pid, v, x, y) { const r = this.ramps[pid].ramp; const i = Math.max(0, Math.min(r.length - 1, Math.floor(v * r.length + BAYER[(y & 3) * 4 + (x & 3)] * 0.9))); return r[i]; }
    // 둥근 덩어리 — 구처럼 명암 (lift: 전체 밝기 보정)
    ell(cx, cy, rx, ry, pid, lift = 0) {
      for (let y = Math.floor(cy - ry); y <= Math.ceil(cy + ry); y++) for (let x = Math.floor(cx - rx); x <= Math.ceil(cx + rx); x++) {
        const nx = (x + 0.5 - cx) / rx, ny = (y + 0.5 - cy) / ry, d = nx * nx + ny * ny;
        if (d > 1) continue;
        const nz = Math.sqrt(1 - d);
        const v = 0.5 + 0.42 * (-nx * 0.55 - ny * 0.6 + nz * 0.45) + lift;
        this.set(x, y, this.tone(pid, v, x, y), pid);
      }
    }
    // 네모 덩어리 — 위 · 왼쪽이 밝고, r 만큼 모서리를 깎는다
    box(x0, y0, w, h, pid, lift = 0, r = 1) {
      for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) {
        const cx = Math.min(x - x0, x0 + w - 1 - x), cy = Math.min(y - y0, y0 + h - 1 - y);
        if (r && cx + cy < r) continue;
        const v = 0.78 - 0.5 * ((y - y0) / Math.max(1, h - 1)) - 0.22 * ((x - x0) / Math.max(1, w - 1)) + lift;
        this.set(x, y, this.tone(pid, v, x, y), pid);
      }
    }
    line(x0, y0, x1, y1, col, pid = -1) {
      const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 1);
      for (let i = 0; i <= n; i++) this.set(x0 + ((x1 - x0) * i) / n, y0 + ((y1 - y0) * i) / n, col, pid);
    }
    // 외곽선 — 바깥과 닿은 가장자리는 그 재질의 가장 어두운 색, 빛 받는 쪽(위 · 왼쪽만 비었으면)은 한 단계 밝게.
    // 먼저 칠한 다른 재질과 닿은 곳도 어두운 선으로 (안쪽 선)
    outline() {
      const out = this.c.slice();
      for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) {
        const pid = this.p[y * this.w + x];
        if (pid < 0 || !this.c[y * this.w + x]) continue;
        const R = this.ramps[pid];
        if (!R.line) continue;
        const e = (dx, dy) => !this.get(x + dx, y + dy);
        const up = e(0, -1), lf = e(-1, 0), dn = e(0, 1), rt = e(1, 0);
        if (dn || rt) out[y * this.w + x] = R.ramp[0];
        else if (up || lf) out[y * this.w + x] = R.ramp[Math.min(1, R.ramp.length - 1)];
        else {
          const behind = [[1, 0], [0, 1], [-1, 0], [0, -1]].some(([dx, dy]) => { const q = this.pid(x + dx, y + dy); return q >= 0 && q < pid && this.ramps[q].line; });
          if (behind) out[y * this.w + x] = R.ramp[0];
        }
      }
      this.c = out;
      return this;
    }
    bake(flip = false) {
      const cv = mkCanvas(this.w, this.h), g = cv.getContext("2d"), img = g.createImageData(this.w, this.h);
      for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) {
        const col = this.c[y * this.w + (flip ? this.w - 1 - x : x)];
        if (!col) continue;
        const n = parseInt(col.slice(1), 16), i = (y * this.w + x) * 4;
        img.data[i] = n >> 16; img.data[i + 1] = (n >> 8) & 255; img.data[i + 2] = n & 255; img.data[i + 3] = 255;
      }
      g.putImageData(img, 0, 0);
      return cv;
    }
  }
  // 흰 실루엣 (맞았을 때 번쩍)
