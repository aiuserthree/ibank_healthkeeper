def item(i: int, rnd: Optional[random.Random] = None) -> dict:
    """i번 문제 한 개 — 보기는 rnd 로 섞는다(없으면 정답이 맨 앞).
    돌려주는 dict(판에 그대로 저장): q 문제 · o 보기 4개 · a 정답 칸(0부터) · c 분야 · l 난이도 · e 해설."""
    cat, level, question, answer, wrongs, note = BANK[i]
    choices = [answer, *wrongs]
    if rnd is not None:
        rnd.shuffle(choices)
    return {"q": question, "o": choices, "a": choices.index(answer), "c": cat, "l": level, "e": note}


_BY: dict = {}


def _pool(cat: str, level: int) -> list:
    if not _BY:
        for i, row in enumerate(BANK):
            _BY.setdefault((row[0], row[1]), []).append(i)
    return _BY.get((cat, level), [])


def pick(rnd: random.Random, plan: tuple = PLAN) -> list:
    """한 판의 문제 — 분야가 겹치지 않게(10문제면 10분야에서 하나씩) plan 의 난이도대로 고르고, 쉬운 문제부터 늘어놓는다.
    보기 순서도 여기서 정한다 — 두 사람이 같은 판을 받는다."""
    cats = list(CATS)
    rnd.shuffle(cats)
    used: set = set()
    out = []
    for slot, level in enumerate(sorted(plan)):
        pool = [i for i in _pool(cats[slot % len(cats)], level) if i not in used]
        if not pool:  # 그 분야에 이 난이도 문제가 모자라면 아무 분야에서
            pool = [i for i, row in enumerate(BANK) if row[1] == level and i not in used]
        i = rnd.choice(pool)
        used.add(i)
        out.append(item(i, rnd))
    return out
