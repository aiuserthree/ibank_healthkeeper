def _jamo_compat(ch: str) -> str:
    """첫가끝 자모(ᄀ · ᅡ · ᆨ)를 키보드로 치는 자모(ㄱ · ㅏ · ㄱ)로."""
    c = ord(ch)
    if 0x1100 <= c <= 0x1112:
        return _CHO[c - 0x1100]
    if 0x1161 <= c <= 0x1175:
        return _JUNG[c - 0x1161]
    if 0x11A8 <= c <= 0x11C2:
        return _JONG[c - 0x11A7]
    return ch


def _fold(text: str) -> str:
    """눈에는 같아 보이는 다른 글자를 하나로 — 쪼개 쓴(NFD) 한글은 붙이고, 전각 영문(ＰＣ)은 반각으로,
    첫가끝 · 반각 자모는 보통 자모로, 한글 채움 글자는 지운다. 화면(words.html 의 fold)도 같은 규칙."""
    text = unicodedata.normalize("NFC", (text or "").translate(_FILLERS))
    return "".join(_jamo_compat(c) for ch in text for c in unicodedata.normalize("NFKC", ch))


def _norm(text: str) -> str:
    """띄어쓰기 · 문장부호 · 대소문자를 빼고 비교한다."""
    return re.sub(r"[\s\W_]+", "", _fold(text).lower())


def _tokens(text: str) -> list:
    """띄어쓰기 · 문장부호로 나눈 토막들."""
    return [t for t in re.split(r"[\s\W_]+", _fold(text).lower()) if t]


# 혼자 흔히 쓰이는 한 글자(안 · 수 · 건 …) — 이런 글자가 든 제시어는 「글자 나눠 쓰기」 토막 검사를 하지 않는다
# (「눈이 안 좋을 때 넣는 약」 같은 보통 설명이 막히지 않게)
_COMMON1 = frozenset("안수건것거게이그저더잘못다또좀때줄뿐듯채걸데")


def _spelled(target: str, tokens: list) -> bool:
    """제시어 글자들이 한 글자짜리 토막으로 차례대로, 사이에 많아야 한 토막을 두고 나오는지 — 「김 그리고 밥」, 「앞은 김 뒤는 밥」."""
    letters = list(target)
    if len(letters) < 2 or any(c in _COMMON1 for c in letters):
        return False
    for i, t in enumerate(tokens):
        if t != letters[0]:
            continue
        at, j = i, 1
        while j < len(letters):
            nxt = next((x for x in range(at + 1, min(at + 3, len(tokens))) if tokens[x] == letters[j]), None)
            if nxt is None:
                break
            at, j = nxt, j + 1
        if j == len(letters):
            return True
    return False


def _clue_error(text: str, prev: list, word: str, banned: tuple, alias: tuple) -> Optional[str]:
    """설명에 걸리는 것이 있으면 오류 코드 — 제시어 · 같은 말 · 금지어, 초성 · 자모, 글자 나눠 쓰기(앞 설명과 이어 붙여도)."""
    flat = _norm(text)
    if any(_norm(w) and _norm(w) in flat for w in (word, *alias, *banned)):
        return "WORDS_BANNED"
    for w in (word, *alias):
        nw = _norm(w)
        if _hangul(w) and len(nw) >= 2 and (_cho(nw) in flat or _jamo(nw) in flat):
            return "WORDS_NO_CHOSUNG"
    before = "".join(_norm(c) for c in prev[-(SPLIT_SPAN - 1):])  # 바로 앞 설명들 — 이번 설명과 이어 붙여 본다
    tokens = _tokens(text)
    for w in (word, *alias):
        nw = _norm(w)
        if len(nw) >= 2 and ((nw in before + flat and nw not in before) or _spelled(nw, tokens)):
            return "WORDS_SPLIT"
    return None


def _syllables(text: str):
    for ch in text:
        code = ord(ch) - 0xAC00
        yield (code // 588, (code % 588) // 28, code % 28) if 0 <= code < 11172 else ch


def _cho(text: str) -> str:
    """초성 — 김밥 → ㄱㅂ (한글이 아닌 글자는 그대로)."""
    return "".join(_CHO[s[0]] if isinstance(s, tuple) else s for s in _syllables(text))


def _jamo(text: str) -> str:
    """자모로 다 쪼갠 모양 — 김밥 → ㄱㅣㅁㅂㅏㅂ."""
    return "".join(_CHO[s[0]] + _JUNG[s[1]] + _JONG[s[2]] if isinstance(s, tuple) else s for s in _syllables(text))


def _hangul(text: str) -> bool:
    return any(0xAC00 <= ord(ch) <= 0xD7A3 for ch in text)


def _explainer(k: dict) -> str:
    return "first" if k["pos"] % 2 == 0 else "second"


def _word(k: dict) -> tuple:
    return WORDS[k["cur"]]


@lru_cache(maxsize=512)
def _deck(seed: int, theme: str, lap: int) -> tuple:
    """판마다 섞은 낱말 순서 — 상태에는 seed 만 두고 그때그때 다시 만든다. 한 바퀴를 다 돌면 다시 섞는다."""
    idx = [i for i, w in enumerate(WORDS) if theme == "all" or w[1] == theme] or list(range(len(WORDS)))
    random.Random(seed * 1009 + lap).shuffle(idx)
    return tuple(idx)


def _pick(k: dict) -> int:
    deck = _deck(k["seed"], k["theme"], 0)
    lap, at = divmod(k["pos"], len(deck))
    return _deck(k["seed"], k["theme"], lap)[at]


def _k(st: dict, write: bool = True) -> dict:
    """낱말 상태 — 예전 모양(1: 맞힌 개수 = 점수, order 목록)이면 지금 모양으로 고쳐 읽는다.
    write=False(화면 보내기)는 저장된 상태를 건드리지 않고 고친 사본만 돌려준다."""
    k = st["k"]
    if k.get("v") == VERSION:
        return k
    if not write:
        k = copy.deepcopy(k)
    i = int(k.get("i", 0) or 0)
    # seed 는 시작 시각으로 정한다 — 화면 보내기(write=False)를 여러 번 해도 같은 낱말이 나오게
    k.setdefault("seed", int(float(k.get("start") or 0) * 1000) % (1 << 30))
    k.setdefault("theme", "all")
    k.setdefault("pos", i)
    if "cur" not in k:
        # 예전 order 는 예전 낱말 목록의 번호라 새 목록에서는 다른 낱말을 가리킨다 — 새 목록에서 다시 고르고,
        # 예전 낱말에 대한 설명 · 답은 비운다(맞히는 사람이 예전 정답을 적어도 틀리지 않게 처음부터)
        k["cur"] = _pick(k)
        k["clues"], k["guesses"], k["hint"] = [], [], False
        k["swapped"] = True  # 끝난 판에서 「풀다 만 낱말」로 엉뚱한 낱말을 보이지 않게
    done = k.get("done") or []
    for key, val in (("score", 0), ("passed", 0), ("right", sum(1 for d in done if d.get("ok"))), ("streak", 0), ("best", 0),
                     ("hint", False), ("hints", 0), ("clues", []), ("guesses", []), ("over", False), ("reason", None), ("gap", {})):
        k.setdefault(key, val)
    k["done"] = [{
        **d, "n": d.get("n", j), "cat": d.get("cat") or _CAT_OF.get(d.get("word"), ""), "hint": bool(d.get("hint")),
        "pts": d.get("pts", 1 if d.get("ok") else 0), "sec": d.get("sec"), "clues": d.get("clues") or [],
    } for j, d in enumerate(done)]
    for old in ("order", "i", "turn"):
        k.pop(old, None)
    k["v"] = VERSION
    if write:
        st["k"] = k
    return k


def _arg(arg) -> tuple:
    """동작 값 — 글자 하나(예전 화면) 또는 {text, n}. n 은 화면이 보고 있던 낱말 번호(바뀌었으면 거절)."""
    if isinstance(arg, dict):
        text, n = arg.get("text"), arg.get("n")
    else:
        text, n = arg, None
    if not isinstance(n, int) or isinstance(n, bool):
        n = None
    if text is None:
        text = ""
    elif not isinstance(text, str):
        text = str(text)
    return text, n


def _finish_word(k: dict, ok: bool, now: float) -> None:
    """지금 낱말을 끝낸다(맞힘 · 넘김) — 점수를 더하고 다음 낱말로, 설명하는 사람이 바뀐다."""
    word, cat, _, _ = _word(k)
    pts = 0
    if ok and k["hint"]:  # 초성을 보고 맞힘 — 1점, 연속 보너스 없이 연속이 끊긴다
        k["streak"] = 0
        pts = HINT_PTS
        k["score"] += pts
        k["right"] += 1
    elif ok:
        k["streak"] += 1
        pts = RIGHT_PTS + (STREAK_BONUS if k["streak"] >= STREAK_FROM else 0)
        k["score"] += pts
        k["right"] += 1
        k["best"] = max(k["best"], k["streak"])
    else:
        k["streak"] = 0
        k["passed"] += 1
    k["done"] = [*k["done"], {
        "n": k["pos"], "word": word, "cat": cat, "ok": ok, "by": _explainer(k), "hint": k["hint"], "pts": pts,
        "streak": k["streak"] if ok else 0, "sec": round(max(0.0, now - k["wordAt"]), 1),
        "clues": [c["text"] for c in k["clues"][-CLUE_SAVE:]], "t": now,
    }][-DONE_KEEP:]
    k["pos"] += 1
    k["cur"] = _pick(k)
    k["clues"], k["guesses"] = [], []
    k["hint"] = False
    k["wordAt"] = now
    k.pop("swapped", None)


