def clean_options(opts: dict) -> dict:
    """대기실 설정 — 주제(theme)만. 키(food) · 이름(음식) 둘 다 받고, 모르는 값은 '전체'."""
    theme = opts.get("theme") if isinstance(opts, dict) else None
    if isinstance(theme, str):
        theme = theme.strip()
        if theme not in THEMES:
            theme = next((key for key, name in THEMES.items() if name == theme), None)
    else:
        theme = None
    return {"theme": theme or "all"}


def start(st: dict, now: float) -> None:
    theme = clean_options(st.get("opts") or {})["theme"]
    seed = random.randrange(1 << 30)
    st["k"] = {
        "v": VERSION, "start": now, "end": now + ROUND_SEC, "seed": seed, "theme": theme,
        "pos": 0, "cur": _deck(seed, theme, 0)[0], "wordAt": now,
        "score": 0, "right": 0, "passed": 0, "streak": 0, "best": 0, "hint": False, "hints": 0,
        "clues": [], "guesses": [], "done": [], "over": False, "reason": None, "gap": {},
    }


def advance(st: dict, now: float) -> bool:
    k = _k(st)
    if k["over"] or now < k["end"]:
        return False
    k["over"], k["reason"] = True, "time"
    return True


def next_event(st: dict) -> Optional[float]:
    k = st["k"]
    return None if k.get("over") else k["end"]


def act(st: dict, side: str, member_id: int, action: str, arg, now: float) -> None:
    k = _k(st)
    if k["over"] or now >= k["end"]:
        raise_app_error("ESCAPE_NOT_PLAYING")
    if action not in ACTIONS:
        raise_app_error("KITCHEN_BAD_ACTION")
    text, n = _arg(arg)
    if n is not None and n != k["pos"]:
        raise_app_error("WORDS_STALE", 409)
    if side not in ROOM.sides:
        raise_app_error("WORDS_NOT_YOUR_TURN")
    explaining = side == _explainer(k)
    word, _, banned, alias = _word(k)
    gap = k["gap"]
    last = gap.get(f"{member_id}:{action}", 0)

    if action == "clue":
        if not explaining:
            raise_app_error("WORDS_NOT_YOUR_TURN")
        if now - last < CLUE_GAP:
            raise_app_error("ESCAPE_TOO_FAST", 429)
        clean = re.sub(r"\s+", " ", text).strip()[:CLUE_MAX]
        if not clean:
            raise_app_error("ESCAPE_CHAT_EMPTY")
        bad = _clue_error(clean, [c["text"] for c in k["clues"]], word, banned, alias)
        if bad:
            raise_app_error(bad)
        gap[f"{member_id}:{action}"] = now
        k["clues"] = [*k["clues"], {"t": now, "text": clean}][-KEEP:]
        return
    if explaining:  # 그 밖(답 · 초성)은 맞히는 사람만
        if action == "pass":
            if now - k["wordAt"] < PASS_MIN:
                raise_app_error("WORDS_PASS_WAIT", 409)
            _finish_word(k, False, now)
            return
        raise_app_error("WORDS_NOT_YOUR_TURN")
    if action == "pass":
        raise_app_error("WORDS_NOT_YOUR_TURN")
    if action == "hint":
        if k["hint"]:
            raise_app_error("WORDS_HINT_USED", 409)
        if not k["clues"] or now - k["wordAt"] < HINT_AFTER:  # 설명을 받아 보고도 막혔을 때만
            raise_app_error("WORDS_HINT_WAIT", 409)
        k["hint"] = True
        k["hints"] += 1
        return
    # guess
    if now - last < GUESS_GAP:
        raise_app_error("ESCAPE_TOO_FAST", 429)
    clean = re.sub(r"\s+", " ", text).strip()[:GUESS_MAX]
    if not clean:
        raise_app_error("ESCAPE_CHAT_EMPTY")
    gap[f"{member_id}:{action}"] = now
    ok = _norm(clean) in {_norm(w) for w in (word, *alias)}
    k["guesses"] = [*k["guesses"], {"t": now, "text": clean, "ok": ok}][-KEEP:]
    if ok:
        _finish_word(k, True, now)


def end_code(st: dict) -> str:
    return "TIME"


def score(st: dict) -> int:
    return int(_k(st, write=False)["score"])


def summary(st: dict) -> str:
    k = _k(st, write=False)
    if not k["right"]:
        return "시간 끝! 이번에는 하나도 못 맞혔어요."
    return f"시간 끝! 낱말 {k['right']}개를 맞혀 {k['score']}점을 모았어요."


def _done_view(d: dict, side: Optional[str], full: bool) -> dict:
    out = {
        "n": d.get("n"), "word": d.get("word"), "cat": CATEGORIES.get(d.get("cat"), ""), "ok": bool(d.get("ok")),
        "hint": bool(d.get("hint")), "pts": d.get("pts", 0), "streak": d.get("streak", 0), "sec": d.get("sec"),
        "me": d.get("by") == side, "t": d.get("t"),
    }
    if full:
        out["clues"] = list(d.get("clues") or [])
    return out


def view(st: dict, side: Optional[str], now: float) -> dict:
    """그 쪽 사람에게 보낼 화면 — 제시어 · 금지어 · 같은 말은 설명하는 사람만(판이 끝나면 둘 다).
    맞히는 사람에게는 분야 · 글자 수, 초성 힌트를 쓴 뒤에만 초성. 초성 힌트를 언제부터 볼 수 있는지는
    wordAt + hintAfter 와 clues(하나 이상)로 화면이 계산한다."""
    k = _k(st, write=False)
    ended = bool(k["over"] or st.get("end"))
    explaining = side == _explainer(k) and not ended
    word, cat, banned, alias = _word(k)
    show = explaining or ended
    done = k["done"] if ended else k["done"][-RECENT:]
    out = {
        "now": now, "start": k["start"], "end": k["end"], "nextAt": next_event(st),
        "over": k["over"], "ended": ended, "n": k["pos"], "wordAt": k["wordAt"],
        "role": "explain" if explaining else "guess",
        "score": k["score"], "right": k["right"], "passed": k["passed"], "streak": k["streak"], "best": k["best"], "hints": k["hints"],
        "theme": k["theme"], "themeName": THEMES.get(k["theme"], "전체"), "cat": CATEGORIES.get(cat, ""),
        "letters": len(word),
        "word": word if show else None,
        "banned": list(banned) if show else None,
        "aliases": list(alias) if show else None,
        "hint": k["hint"],
        "cho": _cho(word) if (k["hint"] or show) else None,
        "clues": k["clues"], "guesses": k["guesses"],
        "done": [_done_view(d, side, ended) for d in done],
        "total": len(k["done"]),
        "clueMax": CLUE_MAX, "guessMax": GUESS_MAX, "passMin": PASS_MIN, "hintAfter": HINT_AFTER,
        "rule": {"right": RIGHT_PTS, "hint": HINT_PTS, "streakFrom": STREAK_FROM, "bonus": STREAK_BONUS, "hintAfter": HINT_AFTER},
        "last": None,
    }
    # 끝났을 때 풀다 만 낱말 — 설명이나 답이 오갔거나 3초 넘게 붙잡고 있었으면 기록 끝에 보여 준다
    if ended and not k.get("swapped") and (k["clues"] or k["guesses"] or min(now, k["end"]) - k["wordAt"] >= 3):
        out["last"] = {
            "word": word, "cat": CATEGORIES.get(cat, ""), "me": _explainer(k) == side, "hint": k["hint"],
            "clues": [c["text"] for c in k["clues"][-CLUE_SAVE:]], "reason": "time" if k["over"] else "stop",
        }
    return out
